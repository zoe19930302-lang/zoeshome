-- 家具家電採購管理網站：Supabase SQL Editor 執行
-- 所有家庭成員需先建立帳號；只有登入使用者可讀寫清單。
-- 這個簡易範本把所有已登入使用者視為同一家庭。若你需要多個家庭彼此隔離，需增加 household_id 與成員表。

create table if not exists public.household_items (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  category text,
  name text not null,
  brand text,
  model text,
  qty numeric not null default 1,
  price numeric not null default 0,
  buy_date date,
  place text,
  status text not null default '未購買',
  delivery_date date,
  delivered_date date,
  photo_url text,
  warranty text,
  warranty_expiry date,
  payment_method text,
  payment_status text,
  deposit numeric not null default 0,
  other_paid numeric not null default 0,
  order_number text,
  receipt_note text,
  room text,
  dimensions text,
  extra_cost numeric not null default 0,
  note text
);

create table if not exists public.household_settings (
  id integer primary key check (id = 1),
  budget numeric not null default 0,
  updated_at timestamptz not null default now()
);
insert into public.household_settings(id,budget) values(1,0) on conflict(id) do nothing;

alter table public.household_items enable row level security;
alter table public.household_settings enable row level security;

drop policy if exists "signed in users can read items" on public.household_items;
create policy "signed in users can read items" on public.household_items
for select to authenticated using (true);
drop policy if exists "signed in users can insert items" on public.household_items;
create policy "signed in users can insert items" on public.household_items
for insert to authenticated with check (true);
drop policy if exists "signed in users can update items" on public.household_items;
create policy "signed in users can update items" on public.household_items
for update to authenticated using (true) with check (true);
drop policy if exists "signed in users can delete items" on public.household_items;
create policy "signed in users can delete items" on public.household_items
for delete to authenticated using (true);

drop policy if exists "signed in users can read settings" on public.household_settings;
create policy "signed in users can read settings" on public.household_settings
for select to authenticated using (true);
drop policy if exists "signed in users can insert settings" on public.household_settings;
create policy "signed in users can insert settings" on public.household_settings
for insert to authenticated with check (true);
drop policy if exists "signed in users can update settings" on public.household_settings;
create policy "signed in users can update settings" on public.household_settings
for update to authenticated using (true) with check (true);
